-- ============================================================
-- 予約ごとの「変更・キャンセル用リンク」トークン
-- ============================================================
-- 顧客はログインせず、予約完了メールに記載したリンク(token付きURL)だけで
-- 自分の予約を照会・キャンセルできるようにする。
--
-- 内部主キー(id)をそのままリンクに使わず、専用のトークン列を分ける理由:
-- 「レコードの識別子」と「その予約を操作できる権限」を混同しないため。
-- 将来トークンだけを再発行・失効させたくなった場合にも、idを変えずに対応できる。

alter table reservations
  add column manage_token uuid not null default gen_random_uuid() unique;

comment on column reservations.manage_token is '予約変更・キャンセルページ(顧客向け、ログイン不要)へのアクセストークン。予約完了メールのリンクに埋め込む。';
